// Prepares the spoken mission-brief narration ONCE and ships it with the game.
// The game itself never calls ElevenLabs — it only plays these files.
//
//   npm run build:briefs
//
// The narrator is "Elderon" for every chapter. There are two ways to get it,
// and this script prefers the first:
//
//  1. RECORDED BY HAND (what chapter 1 uses). Generate the chapter's whole
//     brief in one take on the ElevenLabs website with the Elderon voice, and
//     save it as public/audio/brief/narration/chN.mp3. The recording ships
//     exactly as exported — never re-encoded, never cut — and this script only
//     works out where each written line falls inside it, so the words can be
//     typed in time with the voice. Use this while the account is on a free
//     plan: the site can use voice-library voices, the API cannot.
//
//  2. GENERATED BY API. With no such file, each line is sent to ElevenLabs and
//     saved as its own clip, keyed by a hash of (voice + model + wording) — so
//     re-running only re-generates lines whose wording actually changed. On a
//     free plan the API cannot reach Elderon, so this path falls back to a
//     stand-in voice and says so loudly.
//
// Either way, editing a line in src/content/briefs.json and re-running is all
// it takes; anything unchanged is reused for free.
import { createHash } from 'crypto';
import { promises as fs } from 'fs';
import path from 'path';
import { segmentNarration } from './lib/narration-segments.mjs';

const env = Object.fromEntries(
  (await fs.readFile('.env.local', 'utf8'))
    .split('\n')
    .filter((l) => l.includes('=') && !l.trim().startsWith('#'))
    .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
);
const KEY = env.ELEVENLABS_API_KEY;
if (!KEY) throw new Error('ELEVENLABS_API_KEY missing from .env.local');

/** The narrator. Same voice for all six chapters — it becomes part of the game. */
const NARRATOR = {
  id: env.ELEVENLABS_VOICE_NARRATOR || 'NwyAvGnfbFoNNEi4UuTq',
  name: 'Elderon',
};
/** Used only when the account cannot reach the library voice. */
const STAND_IN = {
  id: env.ELEVENLABS_VOICE_NARRATOR_FALLBACK || 'JBFqnCBsd6RMkjVDRZzb',
  name: 'George (stand-in for Elderon)',
};

const MODEL = 'eleven_multilingual_v2';
const FORMAT = 'mp3_44100_128';
// unhurried and even — a briefing officer, not a trailer
const VOICE_SETTINGS = { stability: 0.6, similarity_boost: 0.75, style: 0.15, speed: 0.86 };

const OUT_DIR = path.join(process.cwd(), 'public', 'audio', 'brief');
/** Where a founder drops a chapter's hand-recorded take: narration/chN.mp3 */
const NARRATION_DIR = path.join(OUT_DIR, 'narration');
const MANIFEST = path.join(OUT_DIR, 'manifest.json');
const lineHash = (voiceId, text) =>
  createHash('sha1').update(`${voiceId}|${MODEL}|${text}`).digest('hex').slice(0, 12);

async function speak(voiceId, text) {
  const res = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}/with-timestamps?output_format=${FORMAT}`,
    {
      method: 'POST',
      headers: { 'xi-api-key': KEY, 'content-type': 'application/json' },
      body: JSON.stringify({ text, model_id: MODEL, voice_settings: VOICE_SETTINGS }),
    },
  );
  if (!res.ok) {
    const detail = await res.text().catch(() => '');
    const err = new Error(`${res.status} ${detail.slice(0, 200)}`);
    err.status = res.status;
    throw err;
  }
  const body = await res.json();
  const align = body.alignment ?? {};
  const starts = align.character_start_times_seconds ?? [];
  const ends = align.character_end_times_seconds ?? [];
  return {
    audio: Buffer.from(body.audio_base64, 'base64'),
    // the API returns a time per character of the text we sent, so the words
    // can be typed on screen exactly as they are spoken
    charStarts: starts.map((s) => Math.round(s * 1000) / 1000),
    duration: Math.round((ends[ends.length - 1] ?? 0) * 1000) / 1000,
  };
}

/** Which voice can this account actually use? Settled before any line is cut,
 *  so a plan that cannot reach the library voice never burns characters
 *  discovering that halfway through. Costs nothing — both checks are free. */
async function resolveVoice() {
  const get = async (url) => {
    const res = await fetch(url, { headers: { 'xi-api-key': KEY } });
    return res.ok ? res.json() : null;
  };
  const mine = await get('https://api.elevenlabs.io/v1/voices');
  const entry = (mine?.voices ?? []).find((v) => v.voice_id === NARRATOR.id);
  // a stock ("premade") voice works on any plan; a voice-library one — which is
  // what Elderon is — needs a paid plan, even though it shows up in the list
  if (entry?.category === 'premade') return NARRATOR;
  const sub = await get('https://api.elevenlabs.io/v1/user/subscription');
  if (entry && sub?.tier && sub.tier !== 'free') return NARRATOR;
  console.warn(
    `\n  ! This ElevenLabs plan cannot use the library voice "${NARRATOR.name}".\n` +
      `    Using ${STAND_IN.name} instead. Upgrade the plan (or add ${NARRATOR.name}\n` +
      `    to the account's voices) and re-run "npm run build:briefs" to switch\n` +
      `    every line to ${NARRATOR.name}.\n`,
  );
  return STAND_IN;
}

const briefs = JSON.parse(await fs.readFile('src/content/briefs.json', 'utf8'));
const previous = await fs
  .readFile(MANIFEST, 'utf8')
  .then(JSON.parse)
  .catch(() => null);

await fs.mkdir(OUT_DIR, { recursive: true });

/** A chapter's hand-recorded single take, if the founders supplied one. */
async function handRecorded(chapterId) {
  const file = path.join(NARRATION_DIR, `${chapterId}.mp3`);
  const bytes = await fs.readFile(file).catch(() => null);
  return bytes ? { file, bytes } : null;
}

// Deciding the voice needs two API calls; skip them when every chapter that
// has lines was recorded by hand (nothing will be sent to ElevenLabs at all).
const chapterIds = Object.keys(briefs.chapters ?? {}).filter(
  (id) => (briefs.chapters[id].lines ?? []).filter((l) => l.trim()).length > 0,
);
const recorded = Object.fromEntries(
  await Promise.all(chapterIds.map(async (id) => [id, await handRecorded(id)])),
);
const needsApi = chapterIds.some((id) => !recorded[id]);

const voice = needsApi ? await resolveVoice() : { id: NARRATOR.id, name: NARRATOR.name };
// a manifest made with a different voice must be re-cut from scratch
const reusable = previous?.voiceId === voice.id ? previous : null;

const manifest = { version: 1, voiceId: voice.id, voiceName: voice.name, chapters: {} };
const keep = new Set(['manifest.json']);
let made = 0;
let reused = 0;

for (const [chapterId, entry] of Object.entries(briefs.chapters ?? {})) {
  const lines = (entry.lines ?? []).map((l) => l.trim()).filter(Boolean);
  if (lines.length === 0) continue;
  const out = [];

  // --- 1. a hand-recorded take: keep it whole, just locate the lines in it ---
  const take = recorded[chapterId];
  if (take) {
    const hash = createHash('sha1').update(take.bytes).digest('hex').slice(0, 12);
    // the ?v= is the recording's own fingerprint: re-record the take and every
    // browser fetches the new one, even though the file name never changes
    const track = `/audio/brief/narration/${chapterId}.mp3?v=${hash}`;
    // reuse is keyed on the recording itself, so which API voice is configured
    // is irrelevant here — read the previous manifest directly
    const prior = previous?.chapters?.[chapterId];
    // reuse only when the stored entry is identical in every respect we would
    // write today — same recording, same wording, same shape
    const unchanged =
      prior?.trackHash === hash &&
      prior.track === track &&
      prior.voiceName &&
      prior.lines?.length === lines.length &&
      prior.lines.every((l, i) => l.text === lines[i] && typeof l.start === 'number');

    if (unchanged) {
      manifest.chapters[chapterId] = prior;
      reused += lines.length;
      console.log(`  reused  ${chapterId}  hand-recorded take, ${lines.length} lines`);
      continue;
    }

    const { lines: timed, duration } = await segmentNarration(take.file, lines);
    manifest.chapters[chapterId] = {
      track,
      trackHash: hash,
      duration,
      voiceName: `${NARRATOR.name} (recorded by hand)`,
      lines: timed,
    };
    made += lines.length;
    console.log(`  timed   ${chapterId}  hand-recorded take (${duration.toFixed(1)}s):`);
    timed.forEach((l, i) => {
      const secs = l.end - l.start;
      console.log(
        `            ${String(i + 1).padStart(2)}. ${l.start.toFixed(2)}–${l.end.toFixed(2)}s ` +
          `(${secs.toFixed(2)}s, ${(l.text.length / secs).toFixed(1)} ch/s)  ${l.text.slice(0, 42)}…`,
      );
    });
    continue;
  }

  // --- 2. no recording: generate the lines one at a time through the API ---
  for (const [i, text] of lines.entries()) {
    const hit = (reusable?.chapters?.[chapterId]?.lines ?? []).find((l) => l.text === text);
    if (hit) {
      const onDisk = await fs
        .access(path.join(process.cwd(), 'public', hit.file))
        .then(() => true)
        .catch(() => false);
      if (onDisk) {
        out.push(hit);
        keep.add(path.basename(hit.file));
        reused++;
        console.log(`  reused  ${chapterId} ${i + 1}/${lines.length}  ${text.slice(0, 46)}…`);
        continue;
      }
    }

    const clip = await speak(voice.id, text);
    const file = `${chapterId}-${String(i + 1).padStart(2, '0')}-${lineHash(voice.id, text)}.mp3`;
    await fs.writeFile(path.join(OUT_DIR, file), clip.audio);
    keep.add(file);
    made++;
    out.push({
      text,
      file: `/audio/brief/${file}`,
      duration: clip.duration,
      charStarts: clip.charStarts,
    });
    console.log(
      `  spoke   ${chapterId} ${i + 1}/${lines.length}  ${clip.duration.toFixed(1)}s  ${text.slice(0, 46)}…`,
    );
  }

  manifest.chapters[chapterId] = { voiceName: voice.name, lines: out };
}

await fs.writeFile(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');

// clips whose wording changed are no longer referenced — clear them out.
// Hand-recorded takes live in narration/ and are the founders' originals:
// never touched here, only ever replaced by hand.
for (const f of await fs.readdir(OUT_DIR, { withFileTypes: true })) {
  if (f.isFile() && !keep.has(f.name)) {
    await fs.unlink(path.join(OUT_DIR, f.name));
    console.log(`  removed ${f.name} (no longer used)`);
  }
}

const byChapter = Object.entries(manifest.chapters)
  .map(([id, c]) => `  ${id}: ${c.voiceName}`)
  .join('\n');
console.log(
  `\nDone — ${made} line(s) prepared, ${reused} reused.\nNarrator per chapter:\n${byChapter}\n\n` +
    `Saved to public/audio/brief/. Commit these files; the game plays them offline.`,
);
